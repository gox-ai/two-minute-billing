/**
 * Generate the dashboard's copy of the event registry from the engine's registry.
 *
 * The dashboard is a separate workspace with its own bundle, so it cannot import
 * `@/modules/events/registry`. That list used to be hand-copied with a "keep in sync"
 * comment, and it drifted 20 types behind — every dispute event among them, plus
 * `refund_settled` and `subscription_pre_debit_notification`. The two pickers it feeds
 * (the webhook endpoint's event-type selector and the events-list filter) could not
 * offer a type the engine emits.
 *
 *   pnpm gen:event-types            write dashboard/lib/api/event-types.ts
 *   pnpm gen:event-types --check    exit 1 if the committed file is stale
 *
 * `test/unit/event-types-generated.test.ts` runs the same check with no DB.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { EVENT_TYPES, resourceTypeOf, type EventType } from "@/modules/events/registry";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const OUT_PATH = join(root, "dashboard", "lib", "api", "event-types.ts");

/**
 * The picker's grouping is NOT the wire envelope's key.
 *
 * `resourceTypeOf` answers "what key does `data` nest under", and it returns the event
 * type unchanged when no resource type prefixes it — `dispute_*` has no registry entry,
 * so it answers `dispute_created` for `dispute_created`. Taken literally that would give
 * the picker six one-item groups. Grouping is presentation, so an unmatched type falls
 * back to its first segment; the delivered payload key is untouched by this file.
 */
function groupKey(type: EventType): string {
  const resource = resourceTypeOf(type);
  return resource === type ? (type.split("_")[0] ?? type) : resource;
}

export function renderEventTypes(): string {
  const groups = new Map<string, string[]>();
  for (const type of EVENT_TYPES) {
    const key = groupKey(type);
    const bucket = groups.get(key);
    if (bucket) bucket.push(type);
    else groups.set(key, [type]);
  }

  // One type per line in both blocks: a new event is then a one-line diff.
  const list = EVENT_TYPES.map((t) => `  "${t}",`).join("\n");
  const grouped = [...groups]
    .map(([key, types]) => `  ${key}: [\n${types.map((t) => `    "${t}",`).join("\n")}\n  ],`)
    .join("\n");

  return `/**
 * GENERATED by \`pnpm gen:event-types\` — do not edit by hand.
 * Source of truth: src/modules/events/registry.ts
 *
 * The dashboard cannot import engine code, so this list is generated rather than
 * copied. It WAS copied, behind a "keep in sync" comment, and sat 20 types behind
 * the engine — the six dispute events, \`refund_settled\`,
 * \`payment_authentication_required\` and \`subscription_pre_debit_notification\` among
 * them — so a selective webhook subscription could not name any of them.
 *
 * \`EVENT_GROUPS\` is for the picker only. The key an event's \`data\` nests under is the
 * engine's business; grouping here is presentation and falls back to the first segment
 * for types with no resource-type entry.
 */
export const EVENT_TYPES = [
${list}
] as const;

export type EventType = (typeof EVENT_TYPES)[number];

const EVENT_GROUPS: Record<string, readonly string[]> = {
${grouped}
};

/** Resource families, in registry order, for the event-type pickers. */
export function groupEventTypes(): Record<string, string[]> {
  return Object.fromEntries(Object.entries(EVENT_GROUPS).map(([key, types]) => [key, [...types]]));
}
`;
}

function main(): void {
  const next = renderEventTypes();
  const check = process.argv.includes("--check");
  const current = readFileSync(OUT_PATH, "utf8");

  if (current === next) {
    console.log(`${OUT_PATH} is current (${EVENT_TYPES.length} event types)`);
    return;
  }
  if (check) {
    console.error(`STALE: ${OUT_PATH} does not match the registry. Run \`pnpm gen:event-types\`.`);
    process.exit(1);
  }
  writeFileSync(OUT_PATH, next);
  console.log(`wrote ${OUT_PATH} (${EVENT_TYPES.length} event types)`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
