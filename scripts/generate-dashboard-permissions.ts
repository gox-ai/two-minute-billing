/**
 * Write `dashboard/lib/permissions.generated.ts` from the engine's permission catalogue.
 * The dashboard cannot import engine code, so it gets a copy; `verify:permission-coverage`
 * fails when the copy is stale.
 *
 *   pnpm permissions:generate
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { KEY_RESOURCES, PERMISSIONS } from "@/modules/auth/permissions";

export const DASHBOARD_CATALOGUE_PATH = new URL(
  "../dashboard/lib/permissions.generated.ts",
  import.meta.url,
).pathname;

export function renderDashboardCatalogue(): string {
  const rows = PERMISSIONS.map(
    (p) =>
      `  { key: ${JSON.stringify(p.key)}, resource: ${JSON.stringify(p.resource)}, mode: ${JSON.stringify(p.mode)}, legacy: ${JSON.stringify(p.legacy)}, area: ${JSON.stringify(p.area)}, label: ${JSON.stringify(p.label)}, operatorOnly: ${!!p.operatorOnly} },`,
  ).join("\n");
  return `// GENERATED by scripts/generate-dashboard-permissions.ts from src/modules/auth/permissions.ts.
// Do not edit. Run \`pnpm permissions:generate\`.

export interface PermissionDef {
  key: string;
  resource: string;
  mode: "read" | "write";
  legacy: "any" | "ops" | "manager" | "developer" | "admin";
  area: string;
  label: string;
  operatorOnly: boolean;
}

export const PERMISSIONS = [
${rows}
] as const satisfies readonly PermissionDef[];

/** Resources an API key permission map may name. */
export const KEY_RESOURCES: readonly string[] = ${JSON.stringify(KEY_RESOURCES)};

export type PermissionKey = (typeof PERMISSIONS)[number]["key"];

const BY_KEY: ReadonlyMap<string, PermissionDef> = new Map(PERMISSIONS.map((p) => [p.key, p]));
export function permissionDef(key: string): PermissionDef | undefined {
  return BY_KEY.get(key);
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(DASHBOARD_CATALOGUE_PATH, renderDashboardCatalogue());
  console.log(`wrote ${DASHBOARD_CATALOGUE_PATH} (${PERMISSIONS.length} permissions)`);
}
